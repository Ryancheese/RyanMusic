export function parseLegalTab(raw?: string | null): LegalTab | null {
  if (raw === 'help' || raw === 'privacy' || raw === 'disclaimer') return raw;
  if (raw === 'disclaimer.php' || raw === 'legal') return 'disclaimer';
  if (raw === 'help.php') return 'help';
  if (raw === 'privacy.php') return 'privacy';
  return null;
}
